  const dig = (tree, key) => key.split('.').reduce((node, part) => (node == null ? undefined : node[part]), tree)

  /** everything the page needs to speak one language */
  function create(code) {
    const locale = locales.find((l) => l.code === code) ?? locales[0]
    const dict = messages[locale.code]
    const plural = new Intl.PluralRules(locale.intl)
    const numbers = new Intl.NumberFormat(locale.intl)
    const months = new Intl.DateTimeFormat(locale.intl, { month: 'short', year: 'numeric' })
    const lists = typeof Intl.ListFormat === 'function' ? new Intl.ListFormat(locale.intl, { style: 'long', type: 'conjunction' }) : null

    const fill = (text, vars = {}) => text.replace(/\{(\w+)\}/g, (_, name) => (vars[name] ?? `{${name}}`))

    function t(key, vars) {
      const found = dig(dict, key) ?? dig(messages.en, key)
      if (typeof found === 'string') return fill(found, vars)
      if (found && typeof found === 'object' && vars && 'count' in vars) {
        const form = found[plural.select(vars.count)] ?? found.other
        return fill(form, { ...vars, count: numbers.format(vars.count) })
      }
      console.warn(`i18n: missing "${key}" for ${locale.code}`)
      return `⟦${key}⟧`
    }

    /** a content value: plain (the same in every language) or { en, hy, ru, fr } */
    const L = (value) => {
      if (value == null) return ''
      if (typeof value === 'object' && !Array.isArray(value)) return value[locale.code] ?? value.en ?? ''
      return value
    }

    // browsers often ship without Armenian month names and quietly fall back to English,
    // so Armenian keeps its own short forms
    const ARMENIAN_MONTHS = ['հունվ.', 'փետր.', 'մարտ', 'ապր.', 'մայիս', 'հունիս', 'հուլիս', 'օգոստ.', 'սեպտ.', 'հոկտ.', 'նոյեմբ.', 'դեկտ.']

    /** '2026-05' → a localized short month and year; '2026' → the year; null → "present" */
    function month(ym) {
      if (!ym) return t('dates.present')
      const [y, m] = String(ym).split('-').map(Number)
      if (!m) return String(y)
      if (locale.code === 'hy') return `${ARMENIAN_MONTHS[m - 1]} ${y} թ.`
      return months.format(new Date(y, m - 1, 15))
    }

    const list = (items) => (lists ? lists.format(items) : items.join(', '))

    return { locale, t, L, month, list, number: (n) => numbers.format(n) }
  }

  window.I18N = { locales, messages, create }
